import json
import time
import os
import sys
import tempfile
import urllib.parse
import urllib.request

OUT = os.environ["TEXTFILE_OUT"]
ENDPOINTS = json.load(open(os.environ["ENDPOINTS_FILE"]))
API_KEY_FILE = os.environ["API_KEY_FILE"]
# Per-model back-off memory between timer firings; see the
# back-off comment in the main loop and hazard 4 in
# modules/apps/llm-metrics.nix.
STATE_FILE = os.path.join(os.environ["STATE_DIRECTORY"], "state.json")

# How long a backed-off child may stay `loaded` before that
# can only mean real traffic is keeping it awake, so a read
# is safe again: twice its own --sleep-idle-seconds, plus
# one timer tick and slack.
#
# Twice, not once, because terra is polled by two collectors
# (amos1 and hpp-1) with no shared state, and each one's
# re-read looks like traffic to the other. A re-read at r
# keeps the child up until r + idle; the other collector
# paused less than idle before r, so with a window over
# 2 x idle its own check falls after the child has already
# slept. With a 1 x idle window the two alternated forever
# once their pauses were more than WAKE_MARGIN apart
# (observed on terra while validating #1010).
WAKE_MARGIN = 90

# Long enough to ride out a busy child answering a metrics
# task behind a decode, short enough that a powered-off
# terra doesn't stall a 1-minute timer.
TIMEOUT = 10

# The four states llama.cpp's router reports
# (server_model_status_to_string). Emitted as a state set,
# the way node_exporter does node_systemd_unit_state, so a
# transition is visible as a series flipping rather than a
# label value changing. Anything unrecognised leaves all
# four at 0.
STATES = ["unloaded", "loading", "loaded", "sleeping"]

# llama.cpp names its metrics "llamacpp:foo", and a colon in
# a metric name is reserved for recording rules — PromQL can
# only reach it through a __name__ matcher, which Grafana
# panels handle badly. Renamed on the way through, and given
# the model/alias labels the source has no room for.
COUNTERS = {
    "llamacpp:prompt_tokens_total": (
        "llama_prompt_tokens_total",
        "Prompt tokens processed by this model since its child process started.",
    ),
    "llamacpp:prompt_seconds_total": (
        "llama_prompt_seconds_total",
        "Seconds spent processing prompts since this model's child process started.",
    ),
    "llamacpp:tokens_predicted_total": (
        "llama_tokens_predicted_total",
        "Tokens generated by this model since its child process started.",
    ),
    "llamacpp:tokens_predicted_seconds_total": (
        "llama_tokens_predicted_seconds_total",
        "Seconds spent generating tokens since this model's child process started.",
    ),
    "llamacpp:n_decode_total": (
        "llama_decode_total",
        "llama_decode() calls since this model's child process started.",
    ),
}
GAUGES = {
    "llamacpp:n_tokens_max": (
        "llama_tokens_max",
        "Largest prompt+generation token count this model has been asked for, against its configured ctxSize.",
    ),
    "llamacpp:requests_processing": (
        "llama_requests_processing",
        "Requests this model is currently serving.",
    ),
}


# What counts as "the model did something since the last
# read". Every counter moves only on real work (prompt eval,
# prediction, decode); a /metrics task moves none of them,
# so two equal readings mean idle rather than "we only saw
# our own scrape".
ACTIVITY = sorted(COUNTERS)
# Everything a backed-off model republishes.
KEPT = set(COUNTERS) | set(GAUGES)


def read_api_key():
    # Missing key is survivable: /v1/models is public, so
    # state still publishes and only the token counters go
    # dark (recorded as llama_model_metrics_error).
    try:
        with open(API_KEY_FILE) as fh:
            return fh.read().strip()
    except OSError as exc:
        sys.stderr.write("api key unreadable: %s\n" % exc)
        return None


def fetch(url, api_key=None):
    req = urllib.request.Request(url)
    if api_key:
        req.add_header("Authorization", "Bearer " + api_key)
    with urllib.request.urlopen(req, timeout=TIMEOUT) as resp:
        return resp.read().decode()


def parse_prometheus(text):
    out = {}
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) == 2:
            try:
                out[parts[0]] = float(parts[1])
            except ValueError:
                pass
    return out


def labels(**kwargs):
    def esc(v):
        return v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

    body = ",".join('%s="%s"' % (k, esc(v)) for k, v in sorted(kwargs.items()))
    return "{" + body + "}"


def load_state():
    # Losing this file is harmless: every loaded model is
    # read once or twice more before it can back off again.
    try:
        with open(STATE_FILE) as fh:
            data = json.load(fh)
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def save_state(data):
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(STATE_FILE), prefix=".state.")
    try:
        with os.fdopen(fd, "w") as fh:
            json.dump(data, fh, sort_keys=True)
        os.rename(tmp, STATE_FILE)
    except BaseException:
        os.unlink(tmp)
        raise


def child_arg(model, flag):
    args = model.get("status", {}).get("args") or []
    for name, value in zip(args, args[1:]):
        if name == flag:
            return value
    return None


def sleep_idle_seconds(model):
    try:
        return float(child_arg(model, "--sleep-idle-seconds"))
    except (TypeError, ValueError):
        return None


def spawn_id(model):
    # The router gives every child a fresh port from
    # get_free_port() and echoes the child's argv in
    # status.args, so the port is a cheap "still the same
    # child" check. It catches an unload + reload landing
    # between two firings, where the state reads `loaded`
    # both times but the counters have reset. If a future
    # router stops echoing it this returns None for every
    # child, which loses that check but keeps the back-off.
    return child_arg(model, "--port")


rows = {}


def emit(metric, mtype, help_text, label_str, value):
    rows.setdefault(metric, (mtype, help_text, []))[2].append((label_str, value))


api_key = read_api_key()
prev_state = load_state()
now = time.time()
next_state = {}

for server in sorted(ENDPOINTS):
    base = ENDPOINTS[server].rstrip("/")
    try:
        models = json.loads(fetch(base + "/v1/models"))["data"]
    except Exception as exc:
        # A powered-off terra lands here every minute. It is
        # a value, not a fault: publish up=0 and move on.
        sys.stderr.write("%s: /v1/models failed: %s\n" % (server, exc))
        emit(
            "llama_server_up",
            "gauge",
            "Whether this llama-server router answered /v1/models.",
            labels(llama_server=server),
            0,
        )
        continue
    emit(
        "llama_server_up",
        "gauge",
        "Whether this llama-server router answered /v1/models.",
        labels(llama_server=server),
        1,
    )

    for model in models:
        name = model["id"]
        # Joined rather than one series per alias: the label
        # is here so a dashboard can legend by role name
        # ("text", "vision", "code") instead of by GGUF, and
        # every model in this fleet has exactly one.
        alias = ",".join(sorted(model.get("aliases") or []))
        state = model.get("status", {}).get("value", "")
        common = dict(llama_server=server, model=name, alias=alias)

        for candidate in STATES:
            emit(
                "llama_model_state",
                "gauge",
                "Router-reported state of this model, one series per state (loaded means resident and awake; sleeping means the child is alive but has handed its VRAM back).",
                labels(state=candidate, **common),
                int(candidate == state),
            )

        # Only an awake model may be asked for /metrics —
        # see the module header. `autoload=false` is the
        # second line of defence for the case where the
        # model sleeps between this check and the request.
        key = "%s\0%s" % (server, name)
        if state != "loaded":
            # Remembered so a sleeping -> loaded transition
            # reads as a wake and the child is read at once.
            next_state[key] = {"state": state}
            continue

        # Back-off (#1010). Every task that reaches the child,
        # this /metrics read included, resets its idle clock,
        # so reading a loaded model every minute keeps it
        # from ever sleeping. Once two consecutive reads of
        # the same child show no work in between, stop
        # reading it and republish the last values, until the
        # router reports that it slept, was replaced, or went
        # away. Tokens it serves while backed off are picked
        # up when it next wakes: the totals live in
        # server_context_impl and survive sleep/wake.
        #
        # A child still `loaded` well past twice its idle
        # timeout since the pause can only be awake because
        # clients are using it, so it is read again then:
        # that read costs no VRAM the traffic wasn't already
        # holding, and keeps a busy model's counters from
        # freezing until it finally sleeps or is evicted.
        child = spawn_id(model)
        prev = prev_state.get(key) or {}
        last = prev.get("values") or {}
        same_child = prev.get("state") == "loaded" and prev.get("spawn") == child
        idle = sleep_idle_seconds(model)
        paused_at = prev.get("paused_at")
        overdue = (
            paused_at is not None
            and idle is not None
            and now - paused_at > 2 * idle + WAKE_MARGIN
        )

        if same_child and paused_at is not None and not overdue:
            parsed = last
            failed = 0
        else:
            url = "%s/metrics?model=%s&autoload=false" % (
                base,
                urllib.parse.quote(name, safe=""),
            )
            try:
                parsed = parse_prometheus(fetch(url, api_key))
                failed = 0
            except Exception as exc:
                sys.stderr.write(
                    "%s: /metrics for %s failed: %s\n" % (server, name, exc)
                )
                parsed = {}
                failed = 1
            # Compare whatever counters this llama.cpp
            # publishes, so a renamed one can't silently
            # disable the back-off.
            seen = [src for src in ACTIVITY if src in parsed]
            if (
                same_child
                and not failed
                and seen
                and parsed.get("llamacpp:requests_processing", 0) == 0
                and all(parsed[src] == last.get(src) for src in seen)
            ):
                paused_at = now
            else:
                paused_at = None

        next_state[key] = {
            "state": state,
            "spawn": child,
            "paused_at": paused_at,
            "values": {k: v for k, v in parsed.items() if k in KEPT},
        }

        # The one silent-failure mode worth a series of its
        # own: this exporter depends on `--metrics` reaching
        # the child through llama.cpp's argv merge, and if
        # that ever stops happening the counters just go
        # quiet while everything else looks healthy.
        emit(
            "llama_model_metrics_error",
            "gauge",
            "Whether the last /metrics read for this loaded model failed.",
            labels(**common),
            failed,
        )
        emit(
            "llama_model_scrape_paused",
            "gauge",
            "Whether this loaded model has gone idle and is no longer being read, so that it can reach sleepIdleSeconds; its counters are republished from the last read.",
            labels(**common),
            int(paused_at is not None),
        )

        for src, (dst, help_text) in COUNTERS.items():
            if src in parsed:
                emit(
                    dst,
                    "counter",
                    help_text
                    + " Resets when the model is evicted; survives sleep/wake.",
                    labels(**common),
                    parsed[src],
                )
        for src, (dst, help_text) in GAUGES.items():
            if src in parsed:
                emit(dst, "gauge", help_text, labels(**common), parsed[src])

# Atomic write via tempfile + rename, so node_exporter never
# reads a half-written file.
fd, tmp = tempfile.mkstemp(dir=os.path.dirname(OUT), prefix=".llama.prom.")
with os.fdopen(fd, "w") as fh:
    for metric in sorted(rows):
        mtype, help_text, samples = rows[metric]
        fh.write("# HELP %s %s\n" % (metric, help_text))
        fh.write("# TYPE %s %s\n" % (metric, mtype))
        for label_str, value in samples:
            fh.write("%s%s %s\n" % (metric, label_str, repr(float(value))))
os.chmod(tmp, 0o644)
os.rename(tmp, OUT)

# An unreachable router's models drop out of the state, so
# they are read fresh when it comes back — right after a
# terra power cycle, where every child is new anyway.
save_state(next_state)
