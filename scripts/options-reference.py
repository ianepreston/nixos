#!/usr/bin/env python3
"""Render the public `my*` option reference (#1026).

Usage: options-reference.py OPTIONS.json > docs/reference/options.md

OPTIONS.json is built by modules/flake/options-reference.nix from the option
declarations (`lib.optionAttrSetToDocList`), never from a host's evaluated
values. Run it through `task docs:options` rather than by hand.

The input is
  {"fixture": str, "groups": [{"title", "intro", "options": [...]}],
   "forbidden": [str]}
where each option carries name, type, description, default, example,
declarations and readOnly, and `default`/`example` are nixpkgs literal values
(`{"_type": "literalExpression" | "literalMD", "text": ...}`), null when the
option has none, or `{"_type": "unrenderable"}` when the default could not be
evaluated without a host.

Rendering fails (exit 1) rather than publish a machine-specific value: when the
output contains a store path or any `forbidden` string (the fixture host's
domain and contact values).
"""

from __future__ import annotations

import json
import re
import sys

HEADER = """\
<!-- Generated by `task docs:options`; do not edit. Change the option
     declaration and regenerate. -->

# Public `my*` option reference

These are the flake's own option surfaces, generated from their `mkOption`
declarations by `task docs:options` (`modules/flake/options-reference.nix`
renders them with `scripts/options-reference.py`). The declaration beside the
code that consumes an option is authoritative; this page is a view of it, and
the `options-reference` flake check fails when it is stale.

Defaults are shown as declared (`defaultText`) where the declaration gives
one, otherwise as evaluated against the option declarations of the
`{fixture}` configuration, without any host's settings. `<name>` in an option
path and `‹name›` in a default stand for the attribute name of an entry in an
attribute set of submodules. Option
descriptions say what an option does; when and why to use it is in
[server app conventions](../server-apps.md) and the
[architecture guide](../agents/architecture.md).
"""

ROLE = re.compile(r"\{(?:option|var|command|env|file|manpage)\}(`[^`]+`)")
CODE_SPAN = re.compile(r"(`+)(?:.+?)\1", re.S)
FENCE = re.compile(r"^\s*(`{3,}|~{3,})")


def escape_html(text: str) -> str:
    """Escape `<`/`>` outside code so `<name>` placeholders stay visible."""
    out, fence = [], None
    for line in text.split("\n"):
        m = FENCE.match(line)
        if fence:
            if m and m.group(1)[0] == fence[0]:
                fence = None
            out.append(line)
            continue
        if m:
            fence = m.group(1)
            out.append(line)
            continue
        parts, last = [], 0
        for c in CODE_SPAN.finditer(line):
            parts.append(
                line[last : c.start()].replace("<", "&lt;").replace(">", "&gt;")
            )
            parts.append(c.group(0))
            last = c.end()
        parts.append(line[last:].replace("<", "&lt;").replace(">", "&gt;"))
        out.append("".join(parts))
    return "\n".join(out)


def description(text: str | None) -> str:
    if not text:
        return "_No description._"
    text = ROLE.sub(r"\1", text.strip())
    return escape_html(text)


def code(text: str) -> str:
    """An inline code span that survives backticks in `text`."""
    run = max((len(m) for m in re.findall(r"`+", text)), default=0)
    ticks = "`" * (run + 1)
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return f"{ticks}{pad}{text}{pad}{ticks}"


def literal(value) -> str | None:
    if value is None:
        return None
    kind = value.get("_type")
    if kind == "unrenderable":
        return "_computed from other options; see the declaration_"
    text = value.get("text", "")
    if kind == "literalMD":
        return escape_html(text.strip())
    if "\n" in text.strip():
        return (
            "\n\n  ```nix\n"
            + "\n".join(f"  {ln}" for ln in text.strip().split("\n"))
            + "\n  ```"
        )
    return code(text)


def declared_in(path: str) -> str:
    if path.startswith("/") or "://" in path:
        return code(path)
    return f"[{code(path)}](../../{path})"


def field(label: str, value: str) -> str:
    # A fenced block starts on its own line; no trailing space before it.
    sep = "" if value.startswith("\n") else " "
    return f"- **{label}:**{sep}{value}"


def render_option(opt: dict) -> str:
    lines = [f"### {code(opt['name'])}", "", description(opt.get("description")), ""]
    lines.append(f"- **Type:** {code(opt['type'])}")
    default = literal(opt.get("default"))
    lines.append(field("Default", default or "none (required)"))
    example = literal(opt.get("example"))
    if example:
        lines.append(field("Example", example))
    if opt.get("readOnly"):
        lines.append("- **Read-only:** set by the declaring module")
    decls = ", ".join(declared_in(d) for d in opt.get("declarations", []))
    if decls:
        lines.append(f"- **Declared in:** {decls}")
    return "\n".join(lines)


def anchor(title: str) -> str:
    return re.sub(r"[^\w\- ]", "", title.lower()).replace(" ", "-")


def render(doc: dict) -> str:
    out = [HEADER.replace("{fixture}", doc["fixture"]), "## Contents", ""]
    for g in doc["groups"]:
        tops = ", ".join(code(n) for n in g["roots"])
        out.append(f"- [{g['title']}](#{anchor(g['title'])}): {tops}")
    for g in doc["groups"]:
        out += ["", f"## {g['title']}", ""]
        if g.get("intro"):
            out += [g["intro"].strip(), ""]
        out.append("\n\n".join(render_option(o) for o in g["options"]))
    return "\n".join(out).rstrip("\n") + "\n"


def leaks(text: str, forbidden: list[str]) -> list[str]:
    found = [f for f in forbidden if f and f in text]
    if "/nix/store/" in text:
        found.append("/nix/store/")
    return found


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__.strip().split("\n\n")[1], file=sys.stderr)
        return 2
    with open(argv[1], encoding="utf-8") as f:
        doc = json.load(f)
    text = render(doc)
    forbidden = doc.get("forbidden", [])
    if leaks(text, forbidden):
        # Name the options, never the values: these may be contact details.
        names = [
            o["name"]
            for g in doc["groups"]
            for o in g["options"]
            if leaks(render_option(o), forbidden)
        ]
        print(
            "options-reference: output contains a store path or a fixture host "
            f"value in: {', '.join(names) or 'the page header'}; give the "
            "option a `defaultText` (or a literal `example`) instead",
            file=sys.stderr,
        )
        return 1
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
