#!/usr/bin/env bash
# Target side of scripts/recovery.sh (#1025). The driver appends variable
# assignments and ONE command line (`restore_volume`, `restore_pg`,
# `restore_sqlite` or `health`) plus a completion marker to this file,
# base64-encodes the result and runs it through `ssh -n <target> "printf %s
# '<base64>' | base64 -d | sudo bash -se"` (restores; plain `bash -se` for the
# probe). The program travels in the ssh command, not on ssh's stdin, so it
# runs even when ssh_config sets `StdinNull yes`, and nothing can read the
# caller's stdin. On its own the file only defines functions and changes
# nothing.
#
# Each action returns normally on success, so the marker line after it runs
# only then. The driver requires that exact line (with a per-run random
# nonce): a program that failed, never ran or was cut short can never count
# as success.
#
# The appended assignments are generated by jq's `@sh` from the validated
# manifest entry, so every value arrives as one single-quoted bash word and
# list values arrive as bash arrays. Nothing here re-splits a value: units,
# paths and swap fields may contain spaces or shell-significant characters.
# The one deliberate expansion is the SQLite live path, which is a glob
# (mySqliteQuiesce) and must resolve to exactly one restored file.
#
# The servers ship bash, coreutils, gawk, gzip, curl, sudo and restic, but no
# python3 or jq, so this side parses no JSON.
#
# Inputs (assigned by the driver):
#   APP                       app name, for messages
#   REPO                      restic repository, <REPO_MOUNT>/restic/<SOURCE_HOST>
#   UNITS=(...)               systemd units stopped before and started after
#   PATHS=(...)               restic --include paths (pg: in addition to
#                             /var/backup/postgresql)
#   DB                        restore_pg: database replayed from pg_dumpall
#   SWAP_STAGED/SWAP_LIVE/SWAP_OWNER=(...)
#                             restore_sqlite: parallel arrays, one entry per
#                             staged-to-live swap; owner `@env@` becomes the
#                             target's server-<env> user
#   URL EXPECT RETRIES SLEEP  health: loopback probe
#   NONCE                     completion-marker nonce (recovery_done)
#
# The restic password is never on the wire: restic reads the target's own
# sops-managed runtime file.
#
# shellcheck disable=SC2154 # inputs are assigned by the driver's preamble
set -euo pipefail

PASS_FILE=/run/secrets/restic/password

# Shutdown is a hard boundary (#1017): every requested unit must stop
# successfully and report inactive before any restore work. Missing units are
# errors too; a recovery target must provide the services named by its
# manifest. A failed stop or restore never reaches start_units — there is no
# error trap that restarts anything.
stop_units() {
  local u state
  for u in "${UNITS[@]}"; do
    echo "[+] Stopping $u"
    if ! systemctl stop "$u"; then
      echo "[!] Failed to stop $u; aborting restore" >&2
      exit 1
    fi
    state=$(systemctl show "$u" --property=ActiveState --value)
    if [ "$state" != inactive ]; then
      echo "[!] $u is $state after stop; aborting restore" >&2
      exit 1
    fi
  done
}

start_units() {
  local u
  for u in "${UNITS[@]}"; do
    echo "[+] Starting $u"
    systemctl start "$u"
  done
}

# `restic unlock` then `--retry-lock 10m`: restore takes a read lock and the
# nightly `forget --prune` holds an exclusive one for ~47s, so an overlapping
# recovery would otherwise abort mid-restore (#676). The unlock is what keeps
# the retry from waiting the full 10m on a stale lock left by a dead process:
# restic's lock acquisition never consults staleness, only `unlock` does.
#
# --delete removes files at the destination, within the included paths, that
# are not in the snapshot: a restore is a clean operation, not an overlay
# (#217).
restic_restore() {
  local includes=() p
  for p in "$@"; do
    includes+=(--include "$p")
  done
  restic -r "$REPO" --password-file "$PASS_FILE" unlock
  restic -r "$REPO" --password-file "$PASS_FILE" --retry-lock 10m \
    restore latest --target / --delete "${includes[@]}"
}

restore_volume() {
  stop_units
  echo "[+] Restoring paths: ${PATHS[*]}"
  restic_restore "${PATHS[@]}"
  start_units
}

restore_pg() {
  stop_units
  echo "[+] Restoring /var/backup/postgresql ${PATHS[*]}"
  restic_restore /var/backup/postgresql "${PATHS[@]}"

  echo "[+] Replaying $DB database from pg_dumpall"
  sudo -u postgres dropdb --if-exists "$DB"
  sudo -u postgres createdb -O "$DB" "$DB"
  # pg_dumpall layout: \connect <db> introduces a section, but CREATE
  # DATABASE <next>; for the SUCCEEDING db appears between the current
  # \connect block and the next \connect — so flip in_target off on both, or
  # psql will try to recreate already-provisioned databases.
  zcat /var/backup/postgresql/all.sql.gz | awk -v db="$DB" '
    /^\\connect / { name = $2; gsub(/"/, "", name); in_target = (name == db); next }
    /^CREATE DATABASE / { in_target = 0; next }
    in_target { print }
  ' | sudo -u postgres psql -v ON_ERROR_STOP=1 "$DB"

  start_units
}

# Expand one live-path glob against the files restic just restored. IFS is
# empty so a path containing spaces is globbed but never word-split.
resolve_live() {
  local IFS=''
  shopt -s nullglob
  # shellcheck disable=SC2206 # the glob expansion is the point
  live=($1)
  shopt -u nullglob
}

restore_sqlite() {
  local server_user i src dst owner live
  server_user=$(getent passwd server-prod >/dev/null && echo server-prod || echo server-dev)

  stop_units
  echo "[+] Restoring paths: ${PATHS[*]}"
  restic_restore "${PATHS[@]}"

  for i in "${!SWAP_LIVE[@]}"; do
    src=${SWAP_STAGED[$i]}
    dst=${SWAP_LIVE[$i]}
    owner=${SWAP_OWNER[$i]//@env@/$server_user}
    # A glob live path (mySqliteQuiesce) must name exactly one file.
    resolve_live "$dst"
    if [ "${#live[@]}" -ne 1 ]; then
      echo "[!] $dst matched ${#live[@]} files, expected 1" >&2
      exit 1
    fi
    dst=${live[0]}
    echo "[+] Swapping $dst <- $src (owner: $owner)"
    install -o "$owner" -g servers -m 0640 "$src" "$dst"
  done

  start_units
}

# Runs as the SSH user, not root: it only curls a loopback URL.
health() {
  local i code=""
  for i in $(seq 1 "$RETRIES"); do
    code=$(curl -s -o /dev/null -w '%{http_code}' "$URL" || true)
    if [ "$code" = "$EXPECT" ]; then
      echo "$APP: $EXPECT OK"
      return 0
    fi
    sleep "$SLEEP"
  done
  echo "$APP: did not return $EXPECT within ${RETRIES}x${SLEEP}s (last code: $code)"
  exit 1
}

# Appended by the driver after the action; reached only when it succeeded.
recovery_done() {
  printf 'RECOVERY-DONE %s\n' "$NONCE"
}
